/**
 * Move datatypes -> TypeScript declarations describing the GraphQL JSON
 * rendering of each value (`MoveValue.json`):
 *   u8/u16/u32 -> number; u64/u128/u256 -> string; address/ID/String/Url/Balance -> string;
 *   vector<u8> -> base64 string; Option<T> -> T | null; enums -> { '@variant': ... }.
 */
import { isOptionType, isScalarDatatype } from '../analysis/events';
import { datatypeKey, formatMoveType, type MoveDatatype, type MoveType } from '../sui/moveTypes';
import { pascalCase } from './naming';

/** datatypeKey -> exported TS identifier. */
export type TypeNames = Map<string, string>;

/** Short names where unique; `ModuleName` on collisions; address suffix as last resort. */
export const assignTypeNames = (datatypes: Iterable<MoveDatatype>): TypeNames => {
  const list = [...datatypes];
  const byName = new Map<string, number>();
  for (const d of list) byName.set(d.name, (byName.get(d.name) ?? 0) + 1);

  const names: TypeNames = new Map();
  const used = new Set<string>();
  for (const d of list) {
    let name = byName.get(d.name)! > 1 ? `${pascalCase(d.module)}${d.name}` : d.name;
    if (used.has(name)) name = `${name}_${d.address.slice(2, 8)}`;
    used.add(name);
    names.set(datatypeKey(d.address, d.module, d.name), name);
  }
  return names;
};

export const isFieldlessEnum = (d: MoveDatatype | undefined): boolean =>
  !!d && d.kind === 'enum' && d.variants.every((v) => v.fields.length === 0);

export const tsTypeFor = (type: MoveType, names: TypeNames): string => {
  switch (type.kind) {
    case 'primitive':
      if (type.name === 'bool') return 'boolean';
      if (type.name === 'u8' || type.name === 'u16' || type.name === 'u32') return 'number';
      return 'string';
    case 'typeParameter':
      return `T${type.index}`;
    case 'vector': {
      if (type.of.kind === 'primitive' && type.of.name === 'u8') return 'string';
      const inner = tsTypeFor(type.of, names);
      return inner.includes('|') ? `(${inner})[]` : `${inner}[]`;
    }
    case 'datatype': {
      if (isOptionType(type)) {
        const inner = type.typeArgs[0] ? tsTypeFor(type.typeArgs[0], names) : 'unknown';
        return `${inner} | null`;
      }
      if (isScalarDatatype(type)) return 'string';
      const name = names.get(datatypeKey(type.address, type.module, type.name));
      if (!name) return 'unknown';
      return type.typeArgs.length
        ? `${name}<${type.typeArgs.map((t) => tsTypeFor(t, names)).join(', ')}>`
        : name;
    }
  }
};

const typeParams = (d: MoveDatatype): string =>
  d.typeParameters.length ? `<${d.typeParameters.map((_, i) => `T${i}`).join(', ')}>` : '';

const renderDatatype = (d: MoveDatatype, names: TypeNames): string => {
  const name = names.get(datatypeKey(d.address, d.module, d.name))!;
  const doc = `/** Move \`${formatMoveType({ kind: 'datatype', address: d.address, module: d.module, name: d.name, typeArgs: [] })}\` (${d.kind}). */`;

  if (d.kind === 'enum') {
    const variants = d.variants.map((v) => {
      const fields = v.fields.map((f) => `; ${f.name}: ${tsTypeFor(f.type, names)}`).join('');
      return `{ '@variant': '${v.name}'${fields} }`;
    });
    return `${doc}\nexport type ${name}${typeParams(d)} =\n  | ${variants.join('\n  | ') || 'never'};`;
  }

  const fields = d.fields.map((f) => `  ${f.name}: ${tsTypeFor(f.type, names)};`).join('\n');
  return `${doc}\nexport interface ${name}${typeParams(d)} {\n${fields}\n}`;
};

/** Full contents of `src/types/moveTypes.ts`. */
export const renderTypesFile = (datatypes: MoveDatatype[], names: TypeNames): string => {
  const sorted = [...datatypes].sort((a, b) =>
    names.get(datatypeKey(a.address, a.module, a.name))!.localeCompare(
      names.get(datatypeKey(b.address, b.module, b.name))!,
    ),
  );
  return [
    '/**',
    ' * GENERATED by sui-events-indexer. Do not edit; regenerate instead.',
    ' *',
    ' * Shapes of Move values as rendered by Sui GraphQL `MoveValue.json`.',
    ' */',
    '',
    sorted.map((d) => renderDatatype(d, names)).join('\n\n'),
    '',
  ].join('\n');
};
