/**
 * Renderers for every GENERATED source file of the scaffolded project.
 * Static (copied verbatim) files live in `templates/`; see `staticFiles.ts`.
 */
import { camelCase } from './naming';
import type { EventTablePlan } from './model';

const HEADER = (purpose: string) =>
  `/**\n * GENERATED by sui-events-indexer. ${purpose}\n */\n`;

/** Exported type identifiers referenced by a TS type string (`Pair<Lock, string>` -> Pair, Lock). */
const typeIdentifiers = (tsType: string): string[] =>
  (tsType.match(/\b[A-Z]\w*/g) ?? []).filter((id) => !/^T\d+$/.test(id));

const genericArgs = (plan: EventTablePlan) =>
  plan.generic
    ? `<${plan.event.datatype.typeParameters.map(() => 'unknown').join(', ')}>`
    : '';

/** `src/db/schema.ts`: one table per event + the cursor table. */
export const renderSchema = (plans: EventTablePlan[]): string => {
  const builders = new Set(['pgTable', 'text', 'timestamp', 'primaryKey', 'index']);
  const jsonTypes = new Set<string>();

  for (const plan of plans) {
    for (const column of plan.columns) {
      builders.add(column.builder.slice(0, column.builder.indexOf('(')));
      if (column.jsonType) for (const id of typeIdentifiers(column.jsonType)) jsonTypes.add(id);
    }
  }

  const tables = plans.map((plan) => {
    const columns = plan.columns.map((c) => {
      const typed = c.jsonType ? `.$type<${c.jsonType}>()` : '';
      const notNull = c.optional ? '' : '.notNull()';
      return `    /** Move \`${c.field}: ${c.moveType}\` */\n    ${c.key}: ${c.builder}${typed}${notNull},`;
    });
    if (plan.generic) columns.unshift(`    suiEventType: text('sui_event_type').notNull(),`);

    return `/** \`${plan.event.definingId}::${plan.dispatchKey}\` */
export const ${plan.tableConst} = pgTable(
  '${plan.table}',
  {
    ...eventColumns(),
${columns.join('\n')}
  },
  (t) => [
    primaryKey({ name: '${plan.table}_pk', columns: [t.suiTxDigest, t.suiEventSeq] }),
    index('${plan.table}_checkpoint_idx').on(t.suiCheckpoint),
    index('${plan.table}_sender_idx').on(t.suiSender),
  ],
);`;
  });

  const typeImport = jsonTypes.size
    ? `import type { ${[...jsonTypes].sort().join(', ')} } from '../types/moveTypes';\n`
    : '';

  return `${HEADER('Regenerate rather than edit; then `bun run db:generate`.')}
import { ${[...builders].sort().join(', ')} } from 'drizzle-orm/pg-core';

${typeImport}import { eventColumns } from './columns';

/** One row per stream: the opaque GraphQL cursor after the last committed page. */
export const indexerCursors = pgTable('indexer_cursors', {
  id: text('id').primaryKey(),
  cursor: text('cursor').notNull(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
});

${tables.join('\n\n')}
`;
};

/** `src/handlers/<module>.ts`: the editable per-module handlers. */
export const renderModuleHandlers = (module: string, plans: EventTablePlan[]): string => {
  const decoders = new Set<string>();
  // Event interfaces plus every type named inside `asJson<...>` instantiations.
  const types = new Set(plans.map((p) => p.typeName));
  for (const plan of plans) {
    for (const c of plan.columns) {
      decoders.add(c.decoder);
      if (c.jsonType) for (const id of typeIdentifiers(c.jsonType)) types.add(id);
    }
  }
  if (plans.some((p) => p.columns.some((c) => c.optional))) decoders.add('asOption');

  const handlers = plans.map((plan) => {
    const values = plan.columns.map((c) => {
      const access = `e.json.${c.field}`;
      // asJson is generic; instantiate it so the insert stays typed against `$type<>()`.
      const decoder = c.jsonType ? `${c.decoder}<${c.jsonType}>` : c.decoder;
      const decode = c.optional
        ? `asOption(${access}, '${c.field}', ${decoder})`
        : `${decoder}(${access}, '${c.field}')`;
      return `          ${c.key}: ${decode},`;
    });
    if (plan.generic) values.unshift(`          suiEventType: e.type,`);

    return `  /** \`${plan.dispatchKey}\` -> \`${plan.table}\` */
  ${plan.event.name}: async (tx, events: IndexedEvent<${plan.typeName}${genericArgs(plan)}>[]) => {
    await tx
      .insert(${plan.tableConst})
      .values(
        events.map((e) => ({
          ...eventMeta(e),
${values.join('\n')}
        })),
      )
      // Replays (restarts, cursor resets) are no-ops: (tx digest, event seq) is the key.
      .onConflictDoNothing();
  },`;
  });

  const exportName = `${camelCase(module)}Handlers`;

  return `/**
 * Handlers for \`${module}\` events.
 *
 * GENERATED as a starting point; edit freely (regenerating overwrites it).
 * Each handler receives a run of consecutive same-type events, in ledger order,
 * inside the transaction that also advances the stream cursor: throw to roll
 * back the whole page, it is retried on the next tick.
 */
import { ${plans.map((p) => p.tableConst).sort().join(', ')} } from '../db/schema';
import { ${[...decoders].sort().join(', ')} } from '../lib/decode';
import type { ${[...types].sort().join(', ')} } from '../types/moveTypes';
import { eventMeta, type Handler, type IndexedEvent } from './types';

export const ${exportName} = {
${handlers.join('\n\n')}
} satisfies Record<string, Handler>;
`;
};

/** `src/handlers/index.ts`: dispatch table keyed by `module::Name`. */
export const renderHandlerIndex = (modules: Map<string, EventTablePlan[]>): string => {
  const imports = [...modules.keys()].map(
    (m) => `import { ${camelCase(m)}Handlers } from './${m}';`,
  );
  const entries = [...modules].flatMap(([m, plans]) =>
    plans.map((p) => `  '${p.dispatchKey}': ${camelCase(m)}Handlers.${p.event.name},`),
  );

  return `${HEADER('Regenerate rather than edit.')}
${imports.join('\n')}
import type { Handler } from './types';

/** \`module::EventName\` -> handler. Address-agnostic: streams already filter by package. */
export const HANDLERS: Record<string, Handler> = {
${entries.join('\n')}
};
`;
};

/** `src/generated/routes.ts`: REST route -> table. */
export const renderRoutes = (plans: EventTablePlan[]): string => `${HEADER('Regenerate rather than edit.')}
import { ${plans.map((p) => p.tableConst).sort().join(', ')} } from '../db/schema';

export const EVENT_ROUTES = [
${plans.map((p) => `  { path: '${p.route}', type: '${p.dispatchKey}', table: ${p.tableConst} },`).join('\n')}
] as const;
`;

export interface GeneratedMeta {
  network: string;
  packageId: string;
  storageId: string;
  version: number;
  eventPackageIds: string[];
  pollingIntervalMs: number;
  generatorVersion: string;
}

/** `src/generated/package.ts`: facts captured at generation time; env overrides them. */
export const renderGeneratedMeta = (meta: GeneratedMeta): string => `${HEADER('Facts captured at generation time; env vars override them (see src/config/env.ts).')}
export const GENERATED = {
  network: '${meta.network}',
  /** Package id passed to the generator. */
  packageId: '${meta.packageId}',
  /** Version analyzed for events (latest at generation time). */
  storageId: '${meta.storageId}',
  version: ${meta.version},
  /** Defining package ids of the event types: one indexer stream each. */
  eventPackageIds: [${meta.eventPackageIds.map((id) => `'${id}'`).join(', ')}],
  pollingIntervalMs: ${meta.pollingIntervalMs},
  generatorVersion: '${meta.generatorVersion}',
} as const;
`;
