/**
 * Package analysis -> in-memory file map -> disk.
 *
 * `buildProjectFiles` is pure (returns path -> contents) so tests can snapshot
 * a whole project without touching the filesystem or the network.
 */
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';

import { collectDatatypes, type EventDefinition, extractEvents } from '../analysis/events';
import type { Network } from '../sui/graphql';
import type { MoveDatatype } from '../sui/moveTypes';
import type { PackageInfo, PackageReader } from '../sui/packageReader';
import { type EventTablePlan, planEventTables } from './model';
import {
  renderGeneratedMeta,
  renderHandlerIndex,
  renderModuleHandlers,
  renderRoutes,
  renderSchema,
} from './render';
import { STATIC_FILES } from './staticFiles';
import { assignTypeNames, renderTypesFile, type TypeNames } from './typescript';
import { GENERATED_DEPENDENCIES, GENERATED_DEV_DEPENDENCIES, MIN_BUN_VERSION } from './versions';

export interface Analysis {
  pkg: PackageInfo;
  events: EventDefinition[];
  datatypes: MoveDatatype[];
  plans: EventTablePlan[];
  /** datatypeKey -> TS identifier, shared by every renderer. */
  names: TypeNames;
  /** Distinct defining package ids of the events: one indexer stream each. */
  eventPackageIds: string[];
}

export const analyzePackage = async (pkg: PackageInfo, reader: PackageReader): Promise<Analysis> => {
  const events = extractEvents(pkg);
  const datatypes = await collectDatatypes(events, pkg.modules, reader);
  const names = assignTypeNames(datatypes.values());
  const plans = planEventTables(events, datatypes, names);
  const eventPackageIds = [...new Set(events.map((e) => e.definingId))].sort();

  return { pkg, events, datatypes: [...datatypes.values()], plans, names, eventPackageIds };
};

export interface ProjectOptions {
  projectName: string;
  network: Network;
  pollingIntervalMs: number;
  generatorVersion: string;
  graphqlUrl?: string;
}

const packageJson = (name: string) => ({
  name,
  version: '0.1.0',
  private: true,
  type: 'module',
  engines: { bun: `>=${MIN_BUN_VERSION}` },
  scripts: {
    indexer: 'bun src/indexer.ts',
    'indexer:dev': 'bun --watch src/indexer.ts',
    api: 'bun src/server.ts',
    'api:dev': 'bun --watch src/server.ts',
    'db:up': 'docker compose up -d --wait',
    'db:generate': 'drizzle-kit generate',
    'db:migrate': 'bun src/db/migrate.ts',
    'db:setup': 'bun run db:generate && bun run db:migrate',
    'db:push': 'drizzle-kit push',
    'db:studio': 'drizzle-kit studio',
    typecheck: 'tsc --noEmit',
    test: 'bun test',
    check: 'bun run typecheck && bun test',
  },
  dependencies: { ...GENERATED_DEPENDENCIES },
  devDependencies: { ...GENERATED_DEV_DEPENDENCIES },
});

const envFile = (name: string, options: ProjectOptions, eventPackageIds: string[]) => {
  const db = name.replace(/[^a-z0-9_]/g, '_');
  return `# Local development defaults. Bun loads this file automatically.
POSTGRES_PORT=5432
DATABASE_URL=postgres://indexer:indexer@localhost:5432/${db}

# Defaults for the next three live in src/generated/package.ts; override per deployment.
# SUI_NETWORK=${options.network}
${options.graphqlUrl ? `SUI_GRAPHQL_URL=${options.graphqlUrl}` : '# SUI_GRAPHQL_URL=https://graphql.mainnet.sui.io/graphql'}
# EVENT_PACKAGE_IDS=${eventPackageIds.join(',')}

POLLING_INTERVAL_MS=${options.pollingIntervalMs}
# IDLE_BACKOFF_MAX_MS=0
# START_CHECKPOINT=
# LOG_LEVEL=info
PORT=3000
`;
};

const dockerCompose = (name: string) => {
  const db = name.replace(/[^a-z0-9_]/g, '_');
  return `services:
  postgres:
    image: postgres:18-alpine
    ports:
      - "\${POSTGRES_PORT:-5432}:5432"
    environment:
      POSTGRES_USER: indexer
      POSTGRES_PASSWORD: indexer
      POSTGRES_DB: ${db}
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U indexer -d ${db}"]
      interval: 2s
      timeout: 3s
      retries: 30
    volumes:
      - postgres_data:/var/lib/postgresql

volumes:
  postgres_data:
`;
};

const readme = (options: ProjectOptions, analysis: Analysis) => `# ${options.projectName}

Sui event indexer for package \`${analysis.pkg.requestedId}\` on **${options.network}**,
generated by \`sui-events-indexer\` ${options.generatorVersion}.

Stack: Bun, \`@mysten/sui\` (GraphQL transport), Drizzle ORM on \`Bun.SQL\`, Postgres.

## Run

\`\`\`bash
bun install
bun run db:up        # Postgres in Docker (POSTGRES_PORT in .env)
bun run db:setup     # drizzle-kit generate + apply migrations
bun run indexer      # stream events into Postgres
bun run api          # REST API on PORT (default 3000)
\`\`\`

## Indexed events

| Event | Table | Route |
|---|---|---|
${analysis.plans.map((p) => `| \`${p.dispatchKey}\` | \`${p.table}\` | \`GET ${p.route}\` |`).join('\n')}

Routes accept \`limit\` (max 500), \`offset\` and \`sender\`; newest first.

## How it indexes

- One stream per defining package id (\`EVENT_PACKAGE_IDS\`): a single GraphQL
  request per tick covers every module of the package.
- Backlogs drain page after page without waiting; once caught up it polls every
  \`POLLING_INTERVAL_MS\` (subsecond values are fine). Empty polls never touch the DB.
- Each page and its cursor commit in one transaction; inserts are idempotent on
  \`(sui_tx_digest, sui_event_seq)\`, so restarts and replays are safe.
- \`IDLE_BACKOFF_MAX_MS\` optionally stretches the interval on quiet packages.

## Layout

\`\`\`
src/
  handlers/<module>.ts   per-module handlers (edit freely; add business logic here)
  db/schema.ts           GENERATED Drizzle tables
  types/moveTypes.ts     GENERATED event JSON types
  generated/             GENERATED package facts + route table
  indexer/stream.ts      polling loop
  sui/client.ts          GraphQL event pages
  server.ts              REST API (Bun.serve routes)
\`\`\`

Regenerating overwrites generated files **and** handlers; commit before regenerating.
After changing \`src/db/schema.ts\`, run \`bun run db:generate && bun run db:migrate\`.
`;

export const buildProjectFiles = (
  analysis: Analysis,
  options: ProjectOptions,
): Map<string, string> => {
  const files = new Map<string, string>(Object.entries(STATIC_FILES));

  const byModule = new Map<string, EventTablePlan[]>();
  for (const plan of analysis.plans) {
    const list = byModule.get(plan.event.module) ?? [];
    list.push(plan);
    byModule.set(plan.event.module, list);
  }

  files.set('package.json', `${JSON.stringify(packageJson(options.projectName), null, 2)}\n`);
  files.set('.env', envFile(options.projectName, options, analysis.eventPackageIds));
  files.set('.env.example', envFile(options.projectName, options, analysis.eventPackageIds));
  files.set('docker-compose.yml', dockerCompose(options.projectName));
  files.set('README.md', readme(options, analysis));
  files.set('src/types/moveTypes.ts', renderTypesFile(analysis.datatypes, analysis.names));
  files.set('src/db/schema.ts', renderSchema(analysis.plans));
  files.set('src/handlers/index.ts', renderHandlerIndex(byModule));
  for (const [module, plans] of byModule) {
    files.set(`src/handlers/${module}.ts`, renderModuleHandlers(module, plans));
  }
  files.set('src/generated/routes.ts', renderRoutes(analysis.plans));
  files.set(
    'src/generated/package.ts',
    renderGeneratedMeta({
      network: options.network,
      packageId: analysis.pkg.requestedId,
      storageId: analysis.pkg.storageId,
      version: analysis.pkg.version,
      eventPackageIds: analysis.eventPackageIds,
      pollingIntervalMs: options.pollingIntervalMs,
      generatorVersion: options.generatorVersion,
    }),
  );

  return files;
};

/** Refuses a non-empty target unless `force`; returns the absolute project dir. */
export const writeProject = async (
  outputDir: string,
  projectName: string,
  files: Map<string, string>,
  force = false,
): Promise<string> => {
  const projectDir = resolve(outputDir, projectName);
  const existing = await readdir(projectDir).catch(() => [] as string[]);
  if (existing.length > 0 && !force) {
    throw new Error(`${projectDir} is not empty; pass --force to overwrite generated files`);
  }

  for (const [path, contents] of files) {
    const target = join(projectDir, path);
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, contents);
  }
  return projectDir;
};
